let lang = 'en';
try {
  const saved = localStorage.getItem('terra-lang');
  lang = saved || ((navigator.language || '').startsWith('es') ? 'es' : 'en');
} catch { /* ignore */ }
export function getLang() { return lang; }
export function setLang(l) { lang = l; try { localStorage.setItem('terra-lang', l); } catch { /* ignore */ } }
export function t(key, vars = {}) {
  let s = STR[lang][key] ?? STR.en[key] ?? key;
  if (typeof s !== 'string') return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}
export const crop = (id) => t(`c_${id}`);
export const month = (m) => STR[lang].months[m];
